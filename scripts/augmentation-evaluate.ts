/**
 * The augmentation layer's advisor study (src/bethesda/augmentation/evaluate.ts).
 *
 *   node scripts/run-ts.mjs scripts/augmentation-evaluate.ts          run it, write docs/benchmarks/fly-augmentation/
 *   node scripts/run-ts.mjs scripts/augmentation-evaluate.ts --check  exit 1 unless a fresh run reproduces it
 *
 * Seeded, observe mode only: the advisor controls nothing. Run it from a
 * clean commit and commit what it writes; a result from a working tree says
 * so and is not a result. Held-out seeds run once: a clean-commit result is
 * never overwritten except by --check. Research subjects only; refuses either
 * production host. Never edit the folder by hand.
 */
import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { arch, platform } from "node:os";
import { join } from "node:path";
import { format, resolveConfig } from "prettier";
import {
  runAdvisorStudy,
  type AdvisorStudyProtocol,
  type AdvisorStudyResult,
} from "../src/bethesda/augmentation/evaluate.js";
import { refuseProductionHost } from "../src/bethesda/firstContact/originals.js";
import { sha256, sha256Json } from "../src/rain/sha256.js";

const root = process.cwd();
const dir = join(root, "docs/benchmarks/fly-augmentation");
const check = process.argv.includes("--check");
const log = (line: string) => console.log(`[augmentation] ${line}`);
refuseProductionHost(dir, existsSync);

const read = (name: string) => {
  try {
    return readFileSync(join(dir, name), "utf8");
  } catch {
    return null;
  }
};
async function emit(name: string, text: string): Promise<boolean> {
  const path = join(dir, name);
  const out = await format(text, {
    ...((await resolveConfig(path)) ?? {}),
    filepath: path,
  });
  const before = read(name);
  if (check) {
    if (before !== out) {
      console.error(`[augmentation] ${name} does not reproduce`);
      return false;
    }
    log(`${name} reproduces`);
    return true;
  }
  mkdirSync(dir, { recursive: true });
  if (before !== out) writeFileSync(path, out);
  log(`${before === out ? "unchanged" : "wrote"} ${name}`);
  return true;
}

interface Stamp {
  ranFrom: string;
  platform: string;
}
const previous = read("giant-fiber.json");
let stamp: Stamp;
if (previous && check) {
  const old = JSON.parse(previous) as Stamp;
  stamp = { ranFrom: old.ranFrom, platform: old.platform };
} else {
  if (previous && (JSON.parse(previous) as Stamp).ranFrom !== "a working tree")
    throw new Error(
      "held-out seeds run once: giant-fiber.json holds a clean-commit result; use --check",
    );
  const dirty = execSync("git status --porcelain", {
    cwd: root,
    encoding: "utf8",
  }).trim();
  stamp = {
    ranFrom: dirty
      ? "a working tree"
      : `\`${execSync("git rev-parse --short HEAD", { cwd: root, encoding: "utf8" }).trim()}\``,
    platform: `Node ${process.versions.node}, ${platform()} ${arch()}`,
  };
}
const text = readFileSync(
  join(root, "src/bethesda/augmentation/protocols/giant-fiber-v1.json"),
  "utf8",
).replace(/\r\n?/g, "\n");
const t0 = performance.now();
const result = runAdvisorStudy(
  JSON.parse(text) as AdvisorStudyProtocol,
  sha256(text),
  sha256Json,
  `docs/benchmarks/fly-augmentation/giant-fiber.json, held-out phase, ran from ${stamp.ranFrom}`,
);
const fmt = (x: number | null, d = 3) => (x === null ? "—" : x.toFixed(d));
const table = (rs: AdvisorStudyResult["heldOut"]) =>
  [
    "| Controller | Hits | Misses | False alarms | Opportunities without an onset | Hit rate | False-alarm rate |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ...rs.byController.map(
      (x) =>
        `| ${x.controller} | ${x.hits} | ${x.misses} | ${x.falseAlarms} | ${x.correctRejections} | ${fmt(x.hitRate)} | ${fmt(x.falseAlarmRate, 6)} |`,
    ),
  ].join("\n");
const readme = [
  "# Neural augmentation: the giant-fiber advisor in observe mode",
  "",
  "Generated by `node scripts/run-ts.mjs scripts/augmentation-evaluate.ts`; never edit this folder by hand. Methods and limits: [docs/FIRST_CONTACT.md](../../FIRST_CONTACT.md#phase-2-the-neural-augmentation-layer).",
  "",
  `Protocol \`${result.protocol.id}\`, SHA-256 \`${result.protocol.sha256}\`; ran from ${stamp.ranFrom} on ${stamp.platform}. Result digest \`${result.digest}\`.`,
  "",
  `The advisor (\`${result.advisor}\`) observed research subjects only and controlled nothing: in observe mode the fly is byte for byte what it is without the layer. An onset is matched within the protocol's window. This compares two models of one reflex (the controller's giant-fiber proxy and Ache et al. 2019's fitted potential); it is not a measurement of a real fly.`,
  "",
  `## Development seeds (${result.development.subjects} subjects per controller)`,
  "",
  table(result.development),
  "",
  `## Held-out seeds (${result.heldOut.subjects} subjects per controller)`,
  "",
  table(result.heldOut),
  "",
  `## The advice gate (criteria: hit rate at least ${result.criteria.minHitRate}, false-alarm rate at most ${result.criteria.maxFalseAlarmRate}, at least ${result.criteria.minEvents} escape events, held-out)`,
  "",
  "| Controller | May advise | Why |",
  "| --- | --- | --- |",
  ...result.gate.map(
    (g) => `| ${g.controller} | ${g.mayAdvise ? "yes" : "no"} | ${g.why} |`,
  ),
  "",
].join("\n");
const ok =
  (await emit("giant-fiber.json", JSON.stringify({ ...stamp, ...result }))) &&
  (await emit("README.md", readme));
log(`${((performance.now() - t0) / 1000).toFixed(0)} s`);
if (!ok) process.exit(1);
