/**
 * The page docs/claims/README.md: what is recomputed, from which records, and
 * what is still only copied. Written from a `Report` and nothing else, so the
 * page cannot say more than the check found.
 */
import { dirname } from "node:path";
import type { BindingResult, DocumentCoverage, Report } from "./check.js";
import { REGISTER } from "./documents.js";

export const REPORT_MD = "docs/claims/README.md";
export const REPORT_JSON = "docs/claims/bindings.json";

/** From docs/claims/ to the repository root. */
const UP = "../..";

/** GitHub's anchor for a heading, as scripts/docs-links.test.ts computes it. */
function slug(heading: string): string {
  return heading
    .replace(/`([^`]*)`/g, "$1")
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M} _-]/gu, "")
    .replace(/ /g, "-");
}

const share = (part: number, of: number) =>
  of === 0 ? "" : `${Math.round((100 * part) / of)}%`;

/** The sentence with its computed parts in bold. */
function marked(r: BindingResult): string {
  const { text, computed } = r.statement!;
  let out = "";
  let at = 0;
  for (const [start, end] of computed) {
    out += `${text.slice(at, start)}<b>${text.slice(start, end)}</b>`;
    at = end;
  }
  return out + text.slice(at);
}

/** Where a sentence's numbers came from, in a few words. */
function provenance(r: BindingResult): string {
  if (r.records.length === 0) return `computed from \`${r.model}\``;
  const folders = [...new Set(r.records.map((f) => dirname(f)))];
  const where =
    r.records.length === 1
      ? `[\`${r.records[0]}\`](${UP}/${r.records[0]})`
      : folders.length === 1
        ? `${r.records.length} records in [\`${folders[0]}/\`](${UP}/${folders[0]}/)`
        : `${r.records.length} records in ${folders.length} folders under \`${commonRoot(folders)}/\``;
  const model = r.model ? `, with \`${r.model}\`` : "";
  return `${where}${model} · evidence \`${r.evidence!.slice(0, 12)}\``;
}

function commonRoot(folders: string[]): string {
  const parts = folders.map((f) => f.split("/"));
  const root: string[] = [];
  for (let i = 0; parts.every((p) => p[i] !== undefined && p[i] === parts[0]![i]); i++)
    root.push(parts[0]![i]!);
  return root.join("/");
}

function coverageTable(
  d: DocumentCoverage,
  link: (key: string, title: string) => string,
) {
  const rows = d.sections
    .filter((s) => s.quantities > 0 || s.bindings.length > 0)
    .map(
      (s) =>
        `| ${link(s.key, s.title)} | ${s.quantities} | ${s.recomputed} | ${share(s.recomputed, s.quantities)} |`,
    );
  return [
    "| Section | Quantities | Recomputed | Share |",
    "| :-- | --: | --: | --: |",
    ...rows,
    `| **All** | **${d.quantities}** | **${d.recomputed}** | **${share(d.recomputed, d.quantities)}** |`,
  ].join("\n");
}

export function renderReport(
  report: Report,
  notRecomputed: Readonly<Record<string, string>>,
): string {
  const held = report.results.filter((r) => r.ok);
  const records = new Set(held.flatMap((r) => r.records));
  const out: string[] = [];
  const say = (...lines: string[]) => out.push(...lines, "");

  say("# The claims, recomputed");
  say(
    "> Generated by `node scripts/run-ts.mjs scripts/claim-bindings.ts --write`. Its `--check`",
    "> and the test suite hold this page to the bindings. Never edit it.",
  );
  say(
    `The [claims register](${UP}/${REGISTER}) and the [README](${UP}/README.md) state numbers`,
    "that were copied from records. A copied number can drift from its record and nothing",
    `fails. The ${held.length} sentences on this page cannot: each is rebuilt from committed`,
    `records by a function in [\`scripts/claims/\`](${UP}/scripts/claims/), and the test suite`,
    "fails when a document and its records disagree.",
  );
  say(
    "This holds a number in a document to the number in its record. It does not show that",
    "the record is right, that the experiment was sound, or that a claim follows from its",
    "numbers. The quantities not listed here are still copied by hand: nothing says they are",
    "wrong, and nothing checks them.",
  );

  say("## How much is recomputed");
  say(
    "| Document | Quantities stated | Recomputed from records | Share |",
    "| :-- | --: | --: | --: |",
    ...report.documents.map(
      (d) =>
        `| [${d.name}](${UP}/${d.path}) | ${d.quantities} | ${d.recomputed} | ${share(d.recomputed, d.quantities)} |`,
    ),
  );
  say(
    `${held.length} sentences, ${records.size} record files. A quantity is a number written in`,
    "digits in a document's prose ([what counts](#what-counts-as-a-quantity)). It is",
    "recomputed only when it lies inside text that a function of the records produced, in a",
    "sentence the document was found to contain. A number that a binding merely quotes is",
    "not counted.",
  );

  for (const d of report.documents) {
    say(`### ${d.name}, section by section`);
    const isRegister = d.path === REGISTER;
    say(
      coverageTable(d, (key, title) =>
        key === "summary"
          ? `[Summary table](${UP}/${d.path}#summary)`
          : `[${key}. ${title}](${UP}/${d.path}#${slug(`${key}. ${title}`)})`,
      ),
    );
    if (isRegister) {
      const silent = d.sections.filter(
        (s) => s.key !== "summary" && s.bindings.length === 0,
      );
      if (silent.length > 0) {
        say("Entries with nothing recomputed, and why:");
        say(
          ...silent.map(
            (s) =>
              `- **${s.key}. ${s.title}.** ${notRecomputed[s.key] ?? "No reason given."}`,
          ),
        );
      }
    }
  }

  say("## The recomputed sentences");
  say(
    "Computed parts are **bold**; the words around them are quoted from the document, and",
    "the check fails if the document stops saying them. Each sentence names the records it",
    "read and one SHA-256 over their paths and digests (first 12 characters here, all of it",
    "and every file's own digest in [`bindings.json`](bindings.json)). A record that changes",
    "changes that digest, so evidence cannot move under a claim unseen.",
  );
  const byDoc = new Map<string, BindingResult[]>();
  for (const r of held) byDoc.set(r.doc, [...(byDoc.get(r.doc) ?? []), r]);
  for (const [doc, results] of byDoc) {
    const coverage = report.documents.find((d) => d.path === doc);
    say(`### ${coverage?.name ?? `\`${doc}\``}`);
    const bySection = new Map<string, BindingResult[]>();
    for (const r of results)
      bySection.set(r.section ?? "", [...(bySection.get(r.section ?? "") ?? []), r]);
    // In the document's own order: the summary table, then the sections by number.
    const order = (key: string) => (key === "summary" ? -1 : Number(key));
    for (const [key, group] of [...bySection].sort(([a], [b]) => order(a) - order(b))) {
      const section = coverage?.sections.find((s) => s.key === key);
      if (section)
        say(`#### ${key === "summary" ? "Summary table" : `${key}. ${section.title}`}`);
      else if (!coverage) say(`From [\`${doc}\`](${UP}/${doc}):`);
      say(
        ...group.map(
          (r) => `- ${marked(r)}<br><sub>\`${r.id}\` · ${provenance(r)}</sub>`,
        ),
      );
    }
  }

  say("## What counts as a quantity");
  say(
    "The rule is in [`scripts/claims/numerals.ts`](../../scripts/claims/numerals.ts), so that",
    "the denominators above are a count anyone can repeat and not a judgement:",
  );
  say(
    "- a number written in digits in prose: `9`, `0.297`, `1,347,336`;",
    "- not anything in code, a link's target, a URL or an HTML tag;",
    "- not a date or a time (`2026-11-04`, `4 November`, `19:27`);",
    "- not an identifier: digits attached to letters (`v783`, `H2`, `ECHO-01`), the far end",
    "  of such a range, or a version of three or more parts;",
    "- not the ordinal of a numbered list or heading, or the number that labels a table row;",
    "- numbers written as words are not seen at all.",
  );

  say("## Checking it yourself");
  say(
    "```bash",
    "node scripts/run-ts.mjs scripts/claim-bindings.ts          # every binding, and the coverage",
    "node scripts/run-ts.mjs scripts/claim-bindings.ts --check  # this page follows from the bindings",
    "npx vitest run scripts/claims                              # and each binding can fail",
    "```",
  );
  say(
    "The last runs every binding against a copy of its document with one computed number",
    "altered, and requires the check to notice: a binding that cannot fail is not a check.",
    "To bind another sentence, see [`scripts/claims/bindings.ts`](../../scripts/claims/bindings.ts).",
  );
  return `${out.join("\n").trimEnd()}\n`;
}
