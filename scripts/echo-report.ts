/** Summarize sealed native ECHO records. Never runs or tunes a controller. */
import { format, resolveConfig } from "prettier";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { FlyRecord } from "../src/rain/scientific/contracts.js";
const archive = "docs/benchmarks/project-echo";
const records = readdirSync(archive)
  .filter((name) => name.startsWith("FLY-"))
  .map((name) => ({
    folder: name,
    record: JSON.parse(
      readFileSync(join(archive, name, "record.json"), "utf8"),
    ) as FlyRecord,
  }));
if (records.length !== 12)
  throw new Error(
    "ECHO summary requires all 12 frozen designs, including negative outcomes",
  );
const fmt = (v: number | null | undefined) =>
  typeof v === "number" ? v.toFixed(4) : "not measured";
const rows = records
  .map(({ folder, record: r }) => {
    const treatment = r.plan.design.parameters.treatment;
    if (!treatment.kind.startsWith("echo_") || !("variant" in treatment))
      throw new Error("Not an ECHO design");
    const metric = r.plan.design.analysis.metric;
    const pairs = r.seeds
      .map((seed) => {
        const control = r.result.runs.find(
          (run) => run.seed === seed && run.arm === "control",
        )?.metrics[metric];
        const treated = r.result.runs.find(
          (run) => run.seed === seed && run.arm === "treatment",
        )?.metrics[metric];
        return typeof control === "number" && typeof treated === "number"
          ? treated - control
          : null;
      })
      .filter((v): v is number => v !== null);
    const mean = pairs.reduce((a, b) => a + b, 0) / pairs.length;
    const sd = Math.sqrt(
      pairs.reduce((a, b) => a + (b - mean) ** 2, 0) / (pairs.length - 1),
    );
    // Eight seeds were preregistered. Student t(7), two-sided 95%; descriptive,
    // approximate, and not the native acceptance rule (which remains sign test).
    const half = pairs.length === 8 ? (2.364624251 * sd) / Math.sqrt(8) : null;
    return {
      folder,
      r,
      protocol: treatment.kind,
      variant: treatment.variant,
      metric,
      ci: half === null ? "not estimated" : `[${fmt(mean - half)}, ${fmt(mean + half)}]`,
    };
  })
  .sort(
    (a, b) =>
      a.protocol.localeCompare(b.protocol) ||
      (a.variant === "full"
        ? -1
        : b.variant === "full"
          ? 1
          : a.variant.localeCompare(b.variant)),
  );
const table = rows
  .map(({ folder, r, protocol, variant, ci }) => {
    const m = r.result.measurements;
    return `| ${protocol} | ${variant} | ${fmt(m.control_mean)} | ${fmt(m.treatment_mean)} | ${fmt(m.mean_paired_delta)} | ${ci} | ${fmt(m.sign_test_p_expected)} | ${r.result.status} / ${r.result.verdict} | [record](benchmarks/project-echo/${folder}/report.md) |`;
  })
  .join("\n");
const diagnostics = rows
  .filter((x) => x.variant === "full")
  .map(({ protocol, r }) => {
    const m = r.result.measurements;
    return `| ${protocol} | ${fmt(m[`treatment_${protocol}_prediction_error_cms`])} | ${fmt(m[`treatment_${protocol}_interval_coverage`])} | ${fmt(m[`treatment_${protocol}_false_self_attribution`])} | ${fmt(m[`treatment_${protocol}_detection_latency_s`])} | ${fmt(m[`treatment_${protocol}_recovery_latency_s`])} |`;
  })
  .join("\n");
const hashes = [...new Set(records.map(({ record: r }) => r.plan.fly_source_sha256))];
const commits = [...new Set(records.map(({ record: r }) => r.code.commit))];
const failures = rows
  .filter(({ r }) => r.result.verdict !== "supported")
  .map(
    ({ protocol, variant, r }) =>
      `- ${protocol}/${variant}: ${r.result.status} (${r.result.verdict}); ${r.result.evaluation ? JSON.stringify(r.result.evaluation) : "no completed evaluation"}`,
  )
  .join("\n");
const text = `# Project ECHO — retained evaluation results

Generated by \`npm run rain:echo:report\` from all twelve native R.A.I.N. records.
Every outcome is included. These are scripted exploratory studies of a
reduced-order simulator, not evidence of subjective consciousness or biological
motor control. The controller and criteria were frozen before these evaluations.

Producing commits: ${commits.map((c) => `\`${c ?? "unknown"}\``).join(", ")}.
Fly source digests: ${hashes.map((h) => `\`${h}\``).join(", ")}.
Development records: ${records.filter(({ record: r }) => r.development).length}.
Total command refusals: ${records.reduce((n, { record: r }) => n + (r.result.measurements.gate_refusals ?? 0), 0)}.

Each row uses eight independently drawn seeds, paired within that design.
Ablations use different host-drawn seed sets: cross-row comparisons are
**descriptive, not matched ablation significance tests**. Trial and temporal
observations within a seed are correlated. CIs are approximate two-sided
Student t intervals for the mean paired difference over eight seeds; bounded
or non-normal metrics need caution. Exact one-sided sign tests and the frozen
minimum effects determine native verdicts. P-values are unadjusted for the
three main hypotheses and nine ablations. A small p-value alone does not pass
the minimum-effect criterion.

| Protocol | Configuration | Control | ECHO | Paired difference | Approx. 95% CI | Expected-direction p | Native outcome | Evidence |
| --- | --- | ---: | ---: | ---: | --- | ---: | --- | --- |
${table}

Impairment and memory errors are cm/s; lower is better. Attribution is a
fraction; higher is better. ECHO-01/02 compare with the disabled self-model
(the causal baseline uses a simple speed residual). ECHO-03 compares with an
explicit reset at re-exposure. Retained learning and episodic-memory benefit
are different hypotheses: compare no_memory descriptively and retain failures.

## Diagnostics of the full configuration

| Protocol | Prediction MAE (cm/s) | Nominal 90% interval coverage | False self-attribution | Detection latency (s) | Recovery latency (s) |
| --- | ---: | ---: | ---: | ---: | ---: |
${diagnostics}

Coverage is measured before each update and is not a guaranteed calibration.
A missing detection is null in the retained trials; the aggregate latency
averages detected trials only and must not be read as a detection-success rate.
Attribution accuracy counts ambiguous/insufficient hypotheses as incorrect.
Trial-level records retain intervention settings, labels and individual
outcomes, so failure in noise, combined interventions or temporary obstruction
is inspectable. Sensor bias can mimic physical drift; causal labels are not
available to the model.

## Non-supported findings

${failures || "All designs met their native criteria; this is still exploratory simulator evidence."}

## Reproduction and scope

\`npm run rain:echo:verify\` checks retained seals, compilation, source provenance,
and exact re-simulation. Original per-design reports, preregistrations, seeds,
trial diagnostics, final hashes and native registry runs remain in the archive.
The original results were not retuned or replaced after inspection.

A self-model checkpoint preserves only that subsystem. It does not restore the
body, random streams, city or pedestrians and cannot establish durable continuity
of a shared fly. Full fly recovery and authoritative single-writer execution
remain unimplemented. See [architecture and protocol](PROJECT_ECHO.md).
`;
writeFileSync(
  "docs/PROJECT_ECHO_RESULTS.md",
  await format(text, {
    ...((await resolveConfig("docs/PROJECT_ECHO_RESULTS.md")) ?? {}),
    filepath: "docs/PROJECT_ECHO_RESULTS.md",
  }),
);
console.log(`Wrote docs/PROJECT_ECHO_RESULTS.md from ${records.length} records`);
