/** The homeostasis study's README, written from its records only (`homeostasis-evaluate.ts report`). */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ARMS = [
  "deployed",
  "no-feedback",
  "full",
  "no-thirst",
  "no-heat",
  "shuffled-humidity",
];
const LABEL: Record<string, string> = {
  deployed:
    "deployed configuration (artificial maintenance on; a reference, not a comparator)",
  "no-feedback": "mortal, no feedback",
  full: "**mortal, thirst and heat feedback**",
  "no-thirst": "mortal, heat feedback only",
  "no-heat": "mortal, thirst feedback only",
  "shuffled-humidity": "mortal, both, humidity read at a displaced point",
};
const f = (x: number | null | undefined, d = 2) =>
  x === null || x === undefined ? "—" : x.toFixed(d);
const iv = (d: { estimate: number; lo: number; hi: number }) =>
  `${f(d.estimate)} [${f(d.lo)}, ${f(d.hi)}]`;

export function report(root: string, outDir: string, id: string): string {
  const L: string[] = [];
  L.push(`# Homeostasis study (${id})`);
  L.push("");
  L.push(
    "Generated by `node scripts/run-ts.mjs scripts/homeostasis-evaluate.ts report` from the records in this folder. Never edit by hand. The design is in [docs/RAIN_GENESIS.md](../../RAIN_GENESIS.md). Every fly is a research subject built from a seed; mortal bodies exist only in this study, and none is Eva or ECHO.",
  );
  L.push("");
  for (const split of ["dev", "heldout"]) {
    const p = join(root, outDir, `${id}-${split}.json`);
    if (!existsSync(p)) {
      L.push(`## ${split}: not run`);
      L.push("");
      continue;
    }
    const r = JSON.parse(readFileSync(p, "utf8"));
    const envs = new Set(r.results.map((x: { environment: number }) => x.environment))
      .size;
    L.push(`## ${split === "dev" ? "Development" : "Held-out"} split`);
    L.push("");
    L.push(
      `Commit \`${String(r.provenance.commit).slice(0, 12)}\`${r.provenance.clean ? "" : " (working tree: not a result)"}, ${r.provenance.platform}, Node ${r.provenance.node}. ${envs} environments × ${r.trials / envs / ARMS.length} flies × ${ARMS.length} arms = ${r.trials} runs of up to 12 simulated hours.`,
    );
    L.push("");
    if (r.criteria) {
      L.push(`**${r.passed} of ${r.of} pre-registered criteria pass.**`);
      L.push("");
      L.push("| Criterion | Result | Measured |");
      L.push("| --- | --- | --- |");
      const C = r.criteria;
      const rows: [string, string, string][] = [
        [
          "H1 (primary): hydrated share, full − no feedback, interval above 0",
          C.H1.pass,
          iv(C.H1.difference),
        ],
        [
          "H2: hydrated share, full − heat only, interval above 0",
          C.H2.pass,
          iv(C.H2.difference),
        ],
        [
          "H3: hydrated share, full − displaced humidity, interval above 0",
          C.H3.pass,
          iv(C.H3.difference),
        ],
        [
          "H4: survival, full − no feedback ≥ 0.25, interval above 0",
          C.H4.pass,
          iv(C.H4.difference),
        ],
        [
          "H5: hours hot, full − thirst only, interval below 0",
          C.H5.pass,
          iv(C.H5.difference),
        ],
        [
          "H6: median hydrated share of the full arm ≥ 0.8",
          C.H6.pass,
          f(C.H6.median_hydrated_share_full),
        ],
      ].map(([a, b, c]) => [a as string, b ? "pass" : "**fail**", c as string]);
      for (const [a, b, c] of rows) L.push(`| ${a} | ${b} | ${c} |`);
      L.push("");
      L.push("Intervals: paired percentile bootstrap over environments, 95%.");
      L.push("");
    }
    L.push(
      "| Arm | Alive at 12 h | Mean hours lived | Mean hydrated share | Mean hours hot | Deaths by cause |",
    );
    L.push("| --- | --- | --- | --- | --- | --- |");
    for (const a of ARMS) {
      const c = r.causes[a] as Record<string, number>;
      const deaths = Object.entries(c)
        .filter(([k]) => k !== "alive")
        .map(([k, v]) => `${k} ${v}`)
        .join(", ");
      L.push(
        `| ${LABEL[a]} | ${f(r.survival[a])} | ${f(r.mean_survived_h[a], 1)} | ${a === "deployed" ? "—" : f(r.mean_hydrated_share[a])} | ${a === "deployed" ? "—" : f(r.mean_hot_h[a], 1)} | ${deaths || "none"} |`,
      );
    }
    L.push("");
  }
  return L.join("\n") + "\n";
}
