/**
 * The human-readable report of one split, rendered from its summary and the
 * machine record alone. Generated, never edited; the verifier re-renders it and
 * compares bytes.
 */
import { CONTROLLERS } from "./controllers.js";
import type { Comparison, Summary } from "./analysis.js";
import { METRIC_UNITS, type Protocol } from "./protocol.js";

export interface MachineRecord {
  schema: "eimb-machine/v1";
  commit: string;
  cleanSources: boolean;
  platform: string;
  arch: string;
  node: string;
  flySourceDigest: string;
  shards: number;
  collectedAt: string;
}

const f = (x: number | null | undefined, d = 3) =>
  x === null || x === undefined || !Number.isFinite(x) ? "n/a" : x.toFixed(d);
const pct = (x: number | null | undefined) =>
  x === null || x === undefined ? "n/a" : `${f(x * 100, 0)}%`;
const ci = (c: { interval: { low: number; high: number; level: number } }, d = 3) =>
  `${f(c.interval.level * 100, 1)}% ${f(c.interval.low, d)} to ${f(c.interval.high, d)}`;

const VERDICT_WORDS: Record<string, string> = {
  IMPROVEMENT: "Improvement demonstrated",
  NO_DEMONSTRATED_IMPROVEMENT: "No demonstrated improvement",
  REGRESSION: "Performance regression",
  INCONCLUSIVE: "Inconclusive evidence",
  INVALID: "Invalid experiment",
};

function comparisonRows(rows: Comparison[], novel?: Set<string>): string[] {
  const out = [
    "| condition | contrast | metric | mean diff | interval | δ | better / worse / tied | sign p | verdict |",
    "| --- | --- | --- | ---: | --- | ---: | --- | ---: | --- |",
  ];
  for (const c of rows)
    out.push(
      `| ${c.condition}${novel?.has(c.condition) ? " (unseen)" : ""} | ${c.contrast[0]} − ${c.contrast[1]} | ${c.metric} | ${f(c.interval.mean)} | ${ci(c)} | ${c.mme} | ${c.interval.better} / ${c.interval.worse} / ${c.interval.tied} | ${f(c.interval.signP, 3)} | **${c.verdict}** |`,
    );
  return out;
}

export function renderReport(s: Summary, p: Protocol, m: MachineRecord): string {
  const L: string[] = [];
  const novel = new Set(p.conditions.filter((c) => c.novelToCandidate).map((c) => c.id));
  L.push(
    `# ECHO Intelligence Metrology Bench: ${p.id}, ${s.split}`,
    "",
    "Generated by `scripts/echo-metrology.ts report` from `records.jsonl`, `protocol.json` and `machine.json` in this folder. Do not edit by hand; `verify` re-renders it and compares bytes.",
    "",
    `**Verdict: ${VERDICT_WORDS[s.verdict.overall]} (${s.verdict.overall}).**`,
    "",
    ...s.verdict.reasons.map((r) => `- ${r}`),
    "",
    "## Identity",
    "",
    `- Protocol \`${p.id}\`, SHA-256 \`${s.protocol.digest}\` (frozen copy: [protocol.json](protocol.json)).`,
    `- Split \`${s.split}\`: ${s.design.seeds.length} research subjects per condition (seeds ${s.design.seeds.length > 8 ? `${s.design.seeds.slice(0, 4).join(", ")} … ${s.design.seeds.at(-1)}` : s.design.seeds.join(", ")}${s.split === "heldout" ? ", derived from the protocol digest" : ", looked at while the bench was built"}), ${s.design.conditions.length} conditions, ${s.design.recordsPresent} runs of ${p.durationS} simulated s (${s.design.complete} complete).`,
    `- Baseline \`${p.baseline}\`; candidate \`${p.candidate}\`; controls ${p.controls.map((c) => `\`${c}\``).join(", ") || "none"}; ablations ${p.ablations.map((c) => `\`${c}\``).join(", ") || "none"}.`,
    `- Code \`${m.commit}\`${m.cleanSources ? "" : " (**sources not clean: a development record, not a result**)"}; fly source digest \`${m.flySourceDigest.slice(0, 16)}…\`; ${m.platform} ${m.arch}, Node ${m.node}, ${m.shards} shard(s).`,
    "- Research subjects only (`research-eimb-…`), born from seeds in the individuality yard. Neither original individual, its store, checkpoints, random streams or runtime is read or touched.",
    "",
    "## Question",
    "",
    `> ${p.question}`,
    "",
    ...p.hypotheses.map((h) => `- ${h}`),
    "",
    "Known before this protocol was frozen:",
    "",
    ...p.priorKnowledge.map((h) => `- ${h}`),
    "",
    `Experimental unit: ${p.experimentalUnit}`,
    "",
    "## Controllers",
    "",
    "| id | role | learns | acts | added parameters | source |",
    "| --- | --- | --- | --- | ---: | --- |",
  );
  for (const id of s.design.controllers) {
    const c = CONTROLLERS[id];
    const role =
      id === p.baseline
        ? "baseline"
        : id === p.candidate
          ? "candidate"
          : p.controls.includes(id)
            ? "control"
            : p.validity.identicalToBaseline.includes(id)
              ? "ablation, validity"
              : "ablation";
    L.push(
      `| \`${id}\` | ${role} | ${c.learns ? "yes" : "no"} | ${c.acts} | ${c.addedParameters} | ${c.source} |`,
    );
  }
  L.push(
    "",
    "## Validity",
    "",
    "| check | passed | detail |",
    "| --- | --- | --- |",
    ...s.validity.checks.map(
      (c) => `| ${c.id} | ${c.passed ? "yes" : "**NO**"} | ${c.detail} |`,
    ),
    "",
    "## Confirmatory endpoints (fixed before the held-out run)",
    "",
    `Bonferroni over ${s.confirmatory.length} endpoint(s): each interval at ${f((1 - p.analysis.alpha / s.confirmatory.length) * 100, 1)}%. Decision rule: ${p.decision.rules[0] ?? ""}`,
    "",
    ...comparisonRows(s.confirmatory, novel),
    "",
    ...s.confirmatory.map(
      (c) =>
        `- ${c.id}: ${c.reason}. δ: ${p.endpoints.confirmatory.find((e) => e.id === c.id)?.mmeRule ?? ""}`,
    ),
    "",
    "## Guardrails",
    "",
    `A guardrail regresses when its ${f((1 - p.analysis.guardrailAlpha) * 100, 0)}% interval lies wholly on the worse side of zero (uncorrected, to stay sensitive to harm).`,
    "",
    "| condition | contrast | metric | mean diff | interval | regression |",
    "| --- | --- | --- | ---: | --- | --- |",
    ...s.guardrails.map(
      (g) =>
        `| ${g.condition} | ${g.contrast.join(" − ")} | ${g.metric} | ${f(g.interval.mean)} | ${ci(g)} | ${g.regression ? "**yes**" : "no"} |`,
    ),
    "",
    "## Where an effect holds: the boundary family",
    "",
    `${p.endpoints.boundary.metric} in every condition, Bonferroni over the family (${s.boundary.length} comparisons), δ = ${p.endpoints.boundary.mme} ${METRIC_UNITS[p.endpoints.boundary.metric]}. "(unseen)" marks conditions the candidate's development never met.`,
    "",
    ...comparisonRows(s.boundary, novel),
    "",
    "## Which part of the mechanism: the 2×2 of learning and acting",
    "",
    ...comparisonRows(s.mechanism, novel),
    "",
    "## Assay sensitivity: did the impairment cost the baseline anything?",
    "",
    "An impairment whose cost to the baseline is not detected leaves nothing to compensate: no controller could show an improvement there, and a null result there says nothing about compensation.",
    "",
    "| condition | metric | baseline here − baseline in reference | interval | reading |",
    "| --- | --- | ---: | --- | --- |",
    ...s.impairmentCost.map(
      (c) =>
        `| ${c.condition} | ${c.metric} | ${f(c.interval.mean)} | ${ci(c)} | ${c.sensitive ? "cost detected" : `cost not detected (${c.reading})`} |`,
    ),
    "",
    "## The six questions",
    "",
    ...s.answers.flatMap((a) => [`**${a.id}. ${a.question}**`, "", a.answer, ""]),
    "## What the controllers learned (internal measures, not behaviour)",
    "",
    "The plasticity's change detection and ECHO's self-model accuracy. These are what the mechanisms compute about themselves; whether they help is decided by the behavioural tables above, never by these.",
    "",
    "| condition | controller | plasticity detected | mean detection s | false alarms | released after recovery | slowed walks / run | self-model belief | converged | mean converge s | end error | calibration 90% (nominal 0.90) | noticed after onset |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: |",
  );
  for (const l of s.learning) {
    const pl = l.plasticity,
      sm = l.selfModel;
    L.push(
      `| ${l.condition} | ${l.controller} | ${pl ? pct(pl.detectedShare) : "—"} | ${pl ? f(pl.detectionMeanS, 0) : "—"} | ${pl ? pct(pl.falseAlarmShare) : "—"} | ${pl && pl.releasedShare !== null ? pct(pl.releasedShare) : "—"} | ${pl ? f(pl.adaptationsMean, 0) : "—"} | ${sm ? sm.target : "—"} | ${sm ? pct(sm.convergedShare) : "—"} | ${sm ? f(sm.convergedMeanS, 0) : "—"} | ${sm ? f(sm.errorEndMean) : "—"} | ${sm ? f(sm.calibration90Mean) : "—"} | ${sm ? f(sm.noticedAfterMean, 1) : "—"} |`,
    );
  }
  L.push(
    "",
    "## Means per condition and controller",
    "",
    "| condition | controller | meals | fed J | late fed J | spent J | collisions | walking blocks | walked m | flown m | restricted latency s | missed | food distance m |",
    "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
  );
  for (const [condition, byC] of Object.entries(s.means))
    for (const [controller, mm] of Object.entries(byC))
      L.push(
        `| ${condition} | ${controller} | ${f(mm.meals, 2)} | ${f(mm.fedJ)} | ${f(mm.lateFedJ)} | ${f(mm.spentJ)} | ${f(mm.collisions, 2)} | ${f(mm.walkingBlocks, 2)} | ${f(mm.walkedM, 2)} | ${f(mm.flownM, 1)} | ${f(mm.restrictedLatencyS, 1)} | ${f(mm.placementsMissed, 2)} | ${f(mm.meanFoodDistanceM, 2)} |`,
      );
  const detected = s.secondary.filter((x) => x.reading !== "no difference detected");
  L.push(
    "",
    "## Secondary contrasts (no claims)",
    "",
    `${s.secondary.length} paired contrasts at 95%, uncorrected. ${detected.length} show a difference; every other interval includes zero. All of them are in [summary.json](summary.json). Read these as leads for a new protocol, never as findings.`,
    "",
    "| condition | contrast | metric | mean diff | interval | reading |",
    "| --- | --- | --- | ---: | --- | --- |",
    ...detected.map(
      (x) =>
        `| ${x.condition} | ${x.contrast.join(" − ")} | ${x.metric} | ${f(x.interval.mean)} | ${ci(x)} | ${x.reading} |`,
    ),
    "",
    "## Failure cases",
    "",
    `The research subjects on which the candidate did worst against the baseline (${p.endpoints.boundary.metric}), per condition.`,
    "",
    "| condition | seed | candidate | baseline | difference | candidate's slowed walks |",
    "| --- | ---: | ---: | ---: | ---: | ---: |",
    ...s.failureCases.map(
      (x) =>
        `| ${x.condition} | ${x.seed} | ${f(x.candidate)} | ${f(x.baseline)} | ${f(x.diff)} | ${x.adaptations ?? "—"} |`,
    ),
    "",
    s.design.failed.length
      ? `Failed or timed-out runs: ${s.design.failed.map((x) => `${x.key} (${x.status}: ${x.error})`).join("; ")}.`
      : "No run failed or timed out.",
    "",
    "## Compute on this machine (never in a verdict)",
    "",
    s.compute.note,
    "",
    "| controller | runs | median wall s | median CPU s | median ticks per wall s |",
    "| --- | ---: | ---: | ---: | ---: |",
    ...Object.entries(s.compute.byController).map(
      ([id, c]) =>
        `| ${id} | ${c.runs} | ${f(c.wallSMedian, 1)} | ${f(c.cpuSMedian, 1)} | ${f(c.ticksPerWallSMedian, 0)} |`,
    ),
    "",
    "## Limits",
    "",
    "- Simulated research flies in one yard. A result here is a statement about these controllers in this simulator, not about real flies or about Eva or ECHO.",
    "- Behavioural records reproduce byte for byte only on the platform they were made on (platform `Math` differs elsewhere); the verifier says when it cannot replay.",
    "- Compute numbers are one machine's, under concurrent shards; they do not transfer to other hardware.",
    `- Stopping rule: ${p.stopping}`,
    "- No benchmark result promotes a controller to either original: that needs a separate owner decision and a continuity validation (docs/ECHO_INTELLIGENCE_METROLOGY.md).",
    "",
    "## Reproduce",
    "",
    "```sh",
    `node scripts/run-ts.mjs scripts/echo-metrology.ts verify --protocol ${p.id} --split ${s.split} --replay 6`,
    `node scripts/run-ts.mjs scripts/echo-metrology.ts run --protocol ${p.id} --split ${s.split} --shard 0/1 --out records.local.jsonl`,
    "```",
    "",
  );
  return L.join("\n");
}
