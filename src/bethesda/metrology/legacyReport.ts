/**
 * The report for the legacy adapter: the reproduction of an existing archive
 * (legacy.ts). The connectome backends' report lives with their adapter in
 * scripts/echo-metrology-connectome.ts, outside src/.
 * Generated, never edited.
 */
import type { ReproductionSummary } from "./legacy.js";
import type { Protocol } from "./protocol.js";
import type { MachineRecord } from "./report.js";

const f = (x: number | null | undefined, d = 3) =>
  x === null || x === undefined || !Number.isFinite(x) ? "n/a" : x.toFixed(d);

export function renderReproduction(s: ReproductionSummary, m: MachineRecord, p: Protocol): string {
  const a = s.primary.archived,
    r = s.primary.reproduced;
  return [
    `# ECHO Intelligence Metrology Bench: reproduction of ${s.source} (${s.sourceCommit.slice(0, 7)})`,
    "",
    "Generated by `scripts/echo-metrology.ts reproduce-report`. Do not edit by hand.",
    "",
    `The 2026-11-07 embodied-plasticity study's held-out \`${s.condition}\` runs (every arm, every seed), re-run with today's code through that study's own \`execute\`, and read through the bench's versioned adapter \`${s.adapter}\`. The study's archive is not changed.`,
    "",
    `- Code \`${m.commit}\`${m.cleanSources ? "" : " (sources not clean)"}; ${m.platform} ${m.arch}, Node ${m.node}; the original ran at \`${s.sourceCommit}\`.`,
    "",
    "## Byte-for-byte reproduction",
    "",
    `**${s.identical} of ${s.runs}** reproduced records are identical to the archived ones (every field, canonical JSON).${s.differing.length ? ` Differing: ${s.differing.join(", ")}.` : ""}`,
    "",
    "## The study's own primary result, recomputed",
    "",
    "Active minus original, meals, weak-legs, with the study's own bootstrap (analysis.ts):",
    "",
    "| | n | mean | 95% interval | better / worse / tied |",
    "| --- | ---: | ---: | --- | --- |",
    `| archived (summary.json) | ${a.n} | ${f(a.mean)} | ${f(a.low)} to ${f(a.high)} | ${a.better} / ${a.worse} / ${a.tied} |`,
    `| recomputed from the reproduced records | ${r.n} | ${f(r.mean)} | ${f(r.low)} to ${f(r.high)} | ${r.better} / ${r.worse} / ${r.tied} |`,
    "",
    s.primary.same
      ? "Identical: the study's verdict, no difference established, reproduces exactly."
      : "**Not identical.** The discrepancy is the finding; the archived result stands as it was recorded.",
    "",
    "## The bench's decision rules applied to the same records",
    "",
    `A re-reading with \`${p.id}\`'s minimum meaningful effects and Bonferroni level, not a new experiment and not a replacement for the study's verdict. These subjects are spent; the bench's own held-out split uses new ones.`,
    "",
    "| metric | contrast | mean | interval | δ | verdict | why |",
    "| --- | --- | ---: | --- | ---: | --- | --- |",
    ...s.benchReading.map(
      (b) =>
        `| ${b.metric} | ${b.contrast.join(" − ")} | ${f(b.interval.mean)} | ${f(b.interval.level * 100, 1)}% ${f(b.interval.low)} to ${f(b.interval.high)} | ${b.mme} | **${b.decision.verdict}** | ${b.decision.reason} |`,
    ),
    "",
  ].join("\n");
}
